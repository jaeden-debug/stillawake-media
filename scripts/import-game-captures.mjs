/**
 * Imports a capture delivery into the site.
 *
 * Reads the capture agent's assets JSON, checks that every file it lists
 * exists under public/, and writes src/data/games/<game>/captured.ts:
 * overrides for ids already declared in media.ts, plus any extra captures.
 *
 * Run: node scripts/import-game-captures.mjs [game-slug]
 * Then: UPDATE_DOCS=1 npx vitest run src/lib/game-docs.test.ts
 */
import fs from "node:fs";
import path from "node:path";

const game = process.argv[2] ?? "stillskin-forest";
const root = process.cwd();
const deliveryPath = path.join(root, "docs/games-platform", game, "capture-delivery", `${game}-assets.json`);
const mediaPath = path.join(root, "src/data/games", game, "media.ts");
const outPath = path.join(root, "src/data/games", game, "captured.ts");

const delivery = JSON.parse(fs.readFileSync(deliveryPath, "utf8"));
const media = fs.readFileSync(mediaPath, "utf8");
const declared = new Set([...media.matchAll(/asset\(\s*"([a-z0-9-]+)"/g)].map((m) => m[1]));

const raw = delivery.capturedAssets;
const items = Array.isArray(raw) ? raw : Object.values(raw);

const overrideFields = ["description", "alt", "dimensions", "aspectRatio", "status", "source", "src", "spoiler"];
const assetFields = ["id", "filename", "gameId", "target", "description", "alt", "use", "dimensions", "aspectRatio", "priority", "spoiler", "liveAvailability", "status", "source", "src"];

const missingFiles = [];
const captured = {};
const extras = [];

for (const a of items) {
  if (!a.src || !fs.existsSync(path.join(root, "public", a.src))) {
    missingFiles.push(a.id);
    continue;
  }
  if (declared.has(a.id)) {
    captured[a.id] = Object.fromEntries(
      overrideFields.filter((f) => f in a).map((f) => [f, f === "status" ? "optimized" : a[f]]),
    );
  } else {
    const asset = Object.fromEntries(assetFields.filter((f) => f in a).map((f) => [f, a[f]]));
    asset.status = "optimized";
    asset.captureInstructions = a.captureInstructions ?? "Extra capture supplied by the capture session.";
    extras.push(asset);
  }
}

if (missingFiles.length) {
  console.error(`Refusing to import: no file under public/ for ${missingFiles.join(", ")}`);
  process.exit(1);
}

const json = (o) => JSON.stringify(o, null, 2);
fs.writeFileSync(
  outPath,
  `import type { MediaAsset } from "@/data/games/types";

/**
 * Captures delivered by the capture session. Generated by
 * scripts/import-game-captures.mjs from
 * docs/games-platform/${game}/capture-delivery/${game}-assets.json
 * (${delivery.generated ?? "undated"}). Real in-game renders; night shots carry a client-side
 * exposure lift, which their descriptions disclose. Do not edit by hand.
 */

/** Overrides for ids already declared in media.ts. */
export const capturedAssets: Record<string, Partial<MediaAsset>> = ${json(captured)};

/** Captures that were not on the original list. */
export const extraAssets: MediaAsset[] = ${json(extras)};
`,
);

console.log(
  `Imported ${Object.keys(captured).length} declared + ${extras.length} extra captures for ${game}. ` +
    `${(delivery.missing ?? []).length} ids still missing.`,
);
